zahl = 10
kommazahl = 10.5
text = "123"

zahl_als_float = float(zahl)
kommazahl_als_int = int(kommazahl)
text_als_int = int(text)

print("Integer converted to float:", zahl_als_float)
print("Type:", type(zahl_als_float))

print("Float converted to integer:", kommazahl_als_int)
print("Type:", type(kommazahl_als_int))

print("String converted to integer:", text_als_int)
print("Type:", type(text_als_int))